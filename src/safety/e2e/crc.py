POLYNOMIAL_0X1D: Final[int] = 0x1D
POLYNOMIAL_0X2F: Final[int] = 0x2F
DEFAULT_CRC_INIT: Final[int] = 0xFF
DEFAULT_CRC_XOR: Final[int] = 0xFF


def generate_crc8_table(poly: int) -> tuple[int, ...]:
    """Generate a 256-entry lookup table for an 8-bit CRC polynomial."""
    table: list[int] = []
    poly_byte = poly & 0xFF
    for byte in range(256):
        curr = byte
        for _ in range(8):
            if curr & 0x80:
                curr = ((curr << 1) ^ poly_byte) & 0xFF
            else:
                curr = (curr << 1) & 0xFF
        table.append(curr)
    return tuple(table)


